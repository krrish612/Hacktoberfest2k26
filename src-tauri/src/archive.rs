//! A tiny, dependency-free ZIP writer.
//!
//! ShutterProof only ever writes one kind of archive: a repair packet holding an
//! HTML report and the evidence files the photographer chose. Those files are
//! already-compressed formats (JPEG, PNG, PDF) and the report is small, so every
//! entry is stored without compression. That keeps the writer small and
//! predictable rather than pulling in a full archive crate.
//!
//! Only "stored" (method 0) entries are produced. The writer emits the byte
//! layout the ZIP format requires — local file headers, a central directory, and
//! an end-of-central-directory record — so the result opens in File Explorer,
//! Finder, and 7-Zip alike.

use std::sync::OnceLock;

use crate::error::{AppError, AppResult};

const LOCAL_HEADER_SIG: u32 = 0x0403_4b50;
const CENTRAL_HEADER_SIG: u32 = 0x0201_4b50;
const EOCD_SIG: u32 = 0x0605_4b50;

const VERSION: u16 = 20; // 2.0, the minimum for the features used here.
const METHOD_STORE: u16 = 0;
const FLAG_UTF8: u16 = 0x0800;

/// A repair packet is capped well below the limits where the 32-bit fields stop
/// being enough, so plain (non-ZIP64) records are always sufficient.
const MAX_ENTRIES: usize = 256;
const MAX_NAME_BYTES: usize = 255;

struct Entry {
    name: Vec<u8>,
    crc: u32,
    size: u32,
    offset: u32,
}

/// The CRC-32 table, built once on first use.
fn crc_table() -> &'static [u32; 256] {
    static TABLE: OnceLock<[u32; 256]> = OnceLock::new();
    TABLE.get_or_init(|| {
        let mut table = [0u32; 256];
        for (index, slot) in table.iter_mut().enumerate() {
            let mut value = index as u32;
            for _ in 0..8 {
                value = if value & 1 == 1 {
                    0xEDB8_8320 ^ (value >> 1)
                } else {
                    value >> 1
                };
            }
            *slot = value;
        }
        table
    })
}

/// The standard CRC-32 (IEEE 802.3) used by every ZIP entry.
pub fn crc32(data: &[u8]) -> u32 {
    let table = crc_table();
    let mut crc = 0xFFFF_FFFFu32;
    for &byte in data {
        crc = table[((crc ^ byte as u32) & 0xFF) as usize] ^ (crc >> 8);
    }
    crc ^ 0xFFFF_FFFF
}

/// Rejects any name that could escape the archive or confuse a reader. Names are
/// generated by the app, so a rejection here means a bug, not bad user input.
fn checked_name(name: &str) -> AppResult<Vec<u8>> {
    let bytes = name.as_bytes();
    let unsafe_name = name.is_empty()
        || bytes.len() > MAX_NAME_BYTES
        || name.starts_with('/')
        || name.ends_with('/')
        || name.contains('\\')
        || name.contains("..")
        || name.contains('\0');
    if unsafe_name {
        return Err(AppError::internal("A packet entry had an unsafe name."));
    }
    Ok(bytes.to_vec())
}

fn push_u16(out: &mut Vec<u8>, value: u16) {
    out.extend_from_slice(&value.to_le_bytes());
}

fn push_u32(out: &mut Vec<u8>, value: u32) {
    out.extend_from_slice(&value.to_le_bytes());
}

/// Builds a ZIP archive in memory.
pub struct ZipWriter {
    out: Vec<u8>,
    entries: Vec<Entry>,
}

impl Default for ZipWriter {
    fn default() -> Self {
        Self::new()
    }
}

impl ZipWriter {
    pub fn new() -> Self {
        Self {
            out: Vec::new(),
            entries: Vec::new(),
        }
    }

    /// Adds one stored entry. The data is copied verbatim.
    pub fn add(&mut self, name: &str, data: &[u8]) -> AppResult<()> {
        if self.entries.len() >= MAX_ENTRIES {
            return Err(AppError::validation("The packet has too many files."));
        }
        let size: u32 = data
            .len()
            .try_into()
            .map_err(|_| AppError::validation("One of the packet files is too large."))?;
        let offset: u32 = self
            .out
            .len()
            .try_into()
            .map_err(|_| AppError::validation("The packet is too large."))?;
        let name = checked_name(name)?;
        let crc = crc32(data);

        push_u32(&mut self.out, LOCAL_HEADER_SIG);
        push_u16(&mut self.out, VERSION);
        push_u16(&mut self.out, FLAG_UTF8);
        push_u16(&mut self.out, METHOD_STORE);
        push_u16(&mut self.out, 0); // last modified time
        push_u16(&mut self.out, 0); // last modified date
        push_u32(&mut self.out, crc);
        push_u32(&mut self.out, size); // compressed size
        push_u32(&mut self.out, size); // uncompressed size
        push_u16(&mut self.out, name.len() as u16);
        push_u16(&mut self.out, 0); // extra field length
        self.out.extend_from_slice(&name);
        self.out.extend_from_slice(data);

        self.entries.push(Entry {
            name,
            crc,
            size,
            offset,
        });
        Ok(())
    }

    /// Writes the central directory and end record, returning the whole archive.
    pub fn finish(mut self) -> Vec<u8> {
        let central_start = self.out.len() as u32;
        for entry in &self.entries {
            push_u32(&mut self.out, CENTRAL_HEADER_SIG);
            push_u16(&mut self.out, VERSION); // version made by
            push_u16(&mut self.out, VERSION); // version needed to extract
            push_u16(&mut self.out, FLAG_UTF8);
            push_u16(&mut self.out, METHOD_STORE);
            push_u16(&mut self.out, 0); // last modified time
            push_u16(&mut self.out, 0); // last modified date
            push_u32(&mut self.out, entry.crc);
            push_u32(&mut self.out, entry.size);
            push_u32(&mut self.out, entry.size);
            push_u16(&mut self.out, entry.name.len() as u16);
            push_u16(&mut self.out, 0); // extra field length
            push_u16(&mut self.out, 0); // file comment length
            push_u16(&mut self.out, 0); // disk number start
            push_u16(&mut self.out, 0); // internal attributes
            push_u32(&mut self.out, 0); // external attributes
            push_u32(&mut self.out, entry.offset);
            self.out.extend_from_slice(&entry.name);
        }
        let central_size = self.out.len() as u32 - central_start;
        let count = self.entries.len() as u16;

        push_u32(&mut self.out, EOCD_SIG);
        push_u16(&mut self.out, 0); // number of this disk
        push_u16(&mut self.out, 0); // disk with the central directory
        push_u16(&mut self.out, count); // entries on this disk
        push_u16(&mut self.out, count); // entries total
        push_u32(&mut self.out, central_size);
        push_u32(&mut self.out, central_start);
        push_u16(&mut self.out, 0); // comment length
        self.out
    }
}

/// Reads back an archive's entry names by walking its local file headers. Used
/// to assert the writer's output in tests; it is not part of the app runtime.
#[cfg(test)]
pub fn read_names(archive: &[u8]) -> Vec<String> {
    let mut names = Vec::new();
    let mut cursor = 0usize;
    while cursor + 30 <= archive.len() {
        let sig = u32::from_le_bytes(archive[cursor..cursor + 4].try_into().unwrap());
        if sig != LOCAL_HEADER_SIG {
            break;
        }
        let size =
            u32::from_le_bytes(archive[cursor + 18..cursor + 22].try_into().unwrap()) as usize;
        let name_len =
            u16::from_le_bytes(archive[cursor + 26..cursor + 28].try_into().unwrap()) as usize;
        let extra_len =
            u16::from_le_bytes(archive[cursor + 28..cursor + 30].try_into().unwrap()) as usize;
        let start = cursor + 30;
        names.push(String::from_utf8_lossy(&archive[start..start + name_len]).to_string());
        cursor = start + name_len + extra_len + size;
    }
    names
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crc32_matches_known_vectors() {
        assert_eq!(crc32(b""), 0);
        assert_eq!(crc32(b"123456789"), 0xCBF4_3926);
        assert_eq!(
            crc32(b"The quick brown fox jumps over the lazy dog"),
            0x414F_A339
        );
    }

    #[test]
    fn writes_a_well_formed_archive() {
        let mut writer = ZipWriter::new();
        writer.add("repair-summary.html", b"<h1>hi</h1>").unwrap();
        writer
            .add("evidence/01-receipt-a.pdf", b"%PDF-1.7")
            .unwrap();
        let archive = writer.finish();

        assert_eq!(&archive[0..4], b"PK\x03\x04");
        assert_eq!(
            &archive[archive.len() - 22..archive.len() - 18],
            b"PK\x05\x06"
        );
        assert_eq!(
            read_names(&archive),
            vec!["repair-summary.html", "evidence/01-receipt-a.pdf"]
        );
    }

    #[test]
    fn rejects_traversal_names() {
        let mut writer = ZipWriter::new();
        assert!(writer.add("../escape.txt", b"x").is_err());
        assert!(writer.add("/absolute.txt", b"x").is_err());
        assert!(writer.add("a\\b.txt", b"x").is_err());
    }
}
